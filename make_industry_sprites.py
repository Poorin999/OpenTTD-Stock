"""Turns the 21 industry pictures (gfx/industry_sprites_128px/NN_name.png, 128 x 111, a 2 x 2 tile building on a diamond) into
src/custom_industry_gfx.cpp and src/custom_industry_gfx.h (GENERATED: edit this file, then run:  python3 make_industry_sprites.py ).
The ORDER of the files is the order of _desert_industries[] in src/desert_industries.cpp.
Each picture is stored with its own palette of up to 63 colours (0 = see-through) and run-length coded. At run time (custom_industry_gfx.cpp) it is cut into
4 ground pieces (one per tile of the 2 x 2 industry, the part of the picture inside that tile's diamond) and 1 building piece (everything outside the diamonds,
it is drawn on top, at the front tile)."""
import sys
from pathlib import Path
from PIL import Image
import numpy as np

HERE = Path(__file__).resolve().parent
SRC = HERE / "gfx" / "industry_sprites_128px"
OUT = HERE / "src"
W, H = 128, 111
MAXCOL = 63

def rle(idx):
    out = []
    run_v, run_n = idx[0], 0
    for v in idx:
        if v == run_v and run_n < 255:
            run_n += 1
        else:
            out += [run_n, run_v]
            run_v, run_n = v, 1
    out += [run_n, run_v]
    return out

def fmt(vals, per=24):
    lines = []
    for i in range(0, len(vals), per):
        lines.append("\t" + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    return "\n".join(lines)

def main():
    files = sorted(SRC.glob("[0-9][0-9]_*.png"))
    if not files:
        sys.exit(f"no pictures in {SRC}")
    blocks, table, names = [], [], []
    for n, f in enumerate(files):
        im = Image.open(f).convert("RGBA")
        if im.size != (W, H):
            sys.exit(f"{f.name}: {im.size}, expected {(W, H)}")
        a = np.array(im)
        alpha = a[..., 3] > 127
        rgb = Image.fromarray(np.where(alpha[..., None], a[..., :3], 128).astype(np.uint8), "RGB")
        q = rgb.quantize(colors=MAXCOL, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        pal = q.getpalette()[:MAXCOL * 3]
        pal += [0] * (MAXCOL * 3 - len(pal))
        idx = np.array(q).astype(np.int32) + 1
        idx[~alpha] = 0
        flat = [int(v) for v in idx.reshape(-1)]
        data = rle(flat)
        palette = [0, 0, 0] + pal  # entry 0 = see-through
        key = f.stem[3:].upper()
        names.append(f.stem)
        blocks.append(f"/** {f.stem}: {len(data)} bytes of run lengths. */\nconstexpr uint8_t PAL_{n}[] = {{\n{fmt(palette)}\n}};\nconstexpr uint8_t RLE_{n}[] = {{\n{fmt(data)}\n}};\n")
        table.append(f"\t{{PAL_{n}, RLE_{n}, sizeof(RLE_{n})}}, // {f.stem}")
