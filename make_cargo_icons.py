def main(out_dir):
    for label, name, rows in ICONS:
        assert len(rows) == 10 and all(len(r) == 10 for r in rows), label
        assert all(c in PALETTE for r in rows for c in r), label
    n = len(ICONS)
    h = HEADER + f'''
/** @file custom_cargo_icons.h Small cargo icons that are drawn by code (no NewGRF, no baseset file). GENERATED by make_cargo_icons.py: edit that file. */

#ifndef CUSTOM_CARGO_ICONS_H
#define CUSTOM_CARGO_ICONS_H

#include <cstdint>

/**
 * The sprite numbers of the icons of the mod. They are far above every sprite of the baseset and of NewGRFs (the sprite number has 24 bits),
 * and they are NOT in the sprite cache table: GetRawSprite() (spritecache.cpp, patched by patch_custom_icons in apply_overlay.py) builds them.
 * The icon of the n-th cargo of FIRS_DESERT (firs_desert_cargo.cpp) is CUSTOM_ICON_SPRITE_BASE + n.
 */
static constexpr uint32_t CUSTOM_ICON_SPRITE_BASE = 0xF00000;
static constexpr uint32_t CUSTOM_ICON_SPRITE_COUNT = {n}; ///< Number of icons.

/** Whether a sprite number is one of the icons of the mod. */
inline bool IsCustomIconSprite(uint32_t sprite)
{{
	return sprite >= CUSTOM_ICON_SPRITE_BASE && sprite < CUSTOM_ICON_SPRITE_BASE + CUSTOM_ICON_SPRITE_COUNT;
}}

/** One icon: width x height palette numbers, row by row, 0 = see-through. */
struct CustomIconData {{
	uint8_t width = 0;
	uint8_t height = 0;
	const uint8_t *pixels = nullptr;
}};

/**
 * Get the picture of an icon.
 * @param sprite Sprite number (see IsCustomIconSprite).
 * @param out The picture.
 * @return True when the number is an icon of the mod.
 */
bool GetCustomIcon(uint32_t sprite, CustomIconData &out);

#endif /* CUSTOM_CARGO_ICONS_H */
'''
    c = HEADER + '''
/** @file custom_cargo_icons.cpp The pictures of the small cargo icons of the mod (10 x 10 pixels, palette colours of the game). GENERATED by make_cargo_icons.py: edit that file. */

#include "stdafx.h"
#include "custom_cargo_icons.h"

#include <iterator>

#include "safeguards.h"

namespace {

/* Palette numbers of the game (see palette_func.h); 0 = see-through. */
'''
    for label, name, rows in ICONS:
        c += f"/** {name} ({label}). */\nconstexpr uint8_t ICON_{label}[10 * 10] = {{\n"
        for r in rows:
            c += "\t" + ", ".join(f"0x{PALETTE[ch][0]:02X}" for ch in r) + ",\n"
        c += "};\n\n"
    c += "/** The icons, in the order of FIRS_DESERT. */\nconstexpr const uint8_t *ICONS[] = {\n"
    for label, name, rows in ICONS:
        c += f"\tICON_{label},\n"
    c += '''};

static_assert(std::size(ICONS) == CUSTOM_ICON_SPRITE_COUNT);

}

bool GetCustomIcon(uint32_t sprite, CustomIconData &out)
{
	if (!IsCustomIconSprite(sprite)) return false;
	out.width = 10;
	out.height = 10;
	out.pixels = ICONS[sprite - CUSTOM_ICON_SPRITE_BASE];
	return true;
}
'''
    out = Path(out_dir)
    (out / "custom_cargo_icons.h").write_text(h, encoding="utf-8")
    (out / "custom_cargo_icons.cpp").write_text(c, encoding="utf-8")
    try:
        from PIL import Image
        scale, pad = 14, 8
        W = n * (10 * scale + pad) + pad
        im = Image.new("RGB", (W, 10 * scale + 2 * pad), (190, 190, 190))
        for i, (label, name, rows) in enumerate(ICONS):
            for y, r in enumerate(rows):
                for x, ch in enumerate(r):
                    col = PALETTE[ch][1]
                    if col:
                        for dy in range(scale):
                            for dx in range(scale):
                                im.putpixel((pad + i * (10 * scale + pad) + x * scale + dx, pad + y * scale + dy), col)
        im.save(out / "cargo-icons-preview.png")
    except ImportError:
        print("Pillow is not installed: no preview picture")
    print(f"{n} icons written to {out}")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
