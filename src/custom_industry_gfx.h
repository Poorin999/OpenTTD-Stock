/** @file custom_industry_gfx.h The own pictures of the desert industries. GENERATED by make_industry_sprites.py: edit that file. */

#ifndef CUSTOM_INDUSTRY_GFX_H
#define CUSTOM_INDUSTRY_GFX_H

#include <cstdint>

/**
 * Sprite numbers of the pictures of the desert industries. Like the cargo icons (custom_cargo_icons.h) they are far above every sprite of the baseset and of
 * NewGRFs and are built by GetRawSprite() (spritecache.cpp, patched by patch_custom_industry_gfx in apply_overlay.py).
 * Industry n (the order of _desert_industries[]) has CUSTOM_INDUSTRY_PARTS sprites: 4 ground pieces (one per tile) and 1 building piece.
 */
static constexpr uint32_t CUSTOM_INDUSTRY_SPRITE_BASE = 0xF10000;
static constexpr uint32_t CUSTOM_INDUSTRY_COUNT = 21;  ///< Number of pictures (industries).
static constexpr uint32_t CUSTOM_INDUSTRY_PARTS = 5;        ///< Sprites per industry: ground 0 .. 3, building 4.

/** Whether a sprite number is a picture of the desert industries. */
inline bool IsCustomIndustrySprite(uint32_t sprite)
{
	return sprite >= CUSTOM_INDUSTRY_SPRITE_BASE && sprite < CUSTOM_INDUSTRY_SPRITE_BASE + CUSTOM_INDUSTRY_COUNT * CUSTOM_INDUSTRY_PARTS;
}

/** The sprite number of piece `part` (0 .. 3 ground of tile 0 .. 3, 4 the building) of industry `n`. */
inline uint32_t CustomIndustrySprite(uint32_t n, uint32_t part)
{
	return CUSTOM_INDUSTRY_SPRITE_BASE + n * CUSTOM_INDUSTRY_PARTS + part;
}

/** One piece. `pixels` and `rgb` stay valid until the next call. */
struct CustomIndustryPicture {
	int width = 0;
	int height = 0;
	int x_offs = 0;
	int y_offs = 0;
	const uint8_t *pixels = nullptr; ///< width x height numbers, 0 = see-through.
	const uint8_t *rgb = nullptr;    ///< 3 bytes (r, g, b) for every number 0 .. 63.
};

/** Cut a piece out of its picture. False when the number is not a picture of the mod. */
bool GetCustomIndustryPicture(uint32_t sprite, CustomIndustryPicture &out);

#endif /* CUSTOM_INDUSTRY_GFX_H */
